# How to Define Functions

def add():
    print(3 + 5)

def greet():
    return("Welcome to our Bootcamp, where we learn Python programming")


def subtract_values():
    value1 = 100
    value2 = 20
    result = value1 - value2
    return(result)

def check_weather():
    weather = "Rainy"
    if weather == "Rainy":
        return("It is better to stay safe from the rain")
    else:
        return("Enjoy the sunshine")


def multiply_values(value1, value2):
    result = value1 * value2
    return(result)


def say_hello(name, age):
    return(f"Hello {name}, you are {age} years old")




