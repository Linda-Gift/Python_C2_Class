#Useful Number Functions:
# abs()

abs_num1 = -10
abs_num2 = -100.5
abs_num3 = -250.30
print(abs(abs_num1))
print(abs(abs_num2))
print(abs(abs_num3))

# round()
round_num1 = 4.7
round_num2 = 4.3
round_num3 = 10000.200
round_num4 = 10000.500
round_num5 = 100.0
print(round(round_num1))
print(round(round_num2))
print(round(round_num3))
print(round(round_num4))
print(round(round_num5))

# max()

max_num1 = max(4.7, 4.3, 10000.200, 10000.500, 100.0)
max_num2 = max(1, 2, 10, 50, 790, 90, 120, 240, 700)
print(max_num1)
print(max_num2)


# min()
min_num1 = min(4.7, 4.3, 10000.200, 10000.500, 100.0)
min_num2 = min(1, 2, 10, 50, 790, 90, 120, 240, 700)
print(min_num1)
print(min_num2)


# pow()

number = 8 ** 4
pow_num1 = pow(8, 4)
print(number)
print(pow_num1)

